#!/usr/bin/env node
/* Bakes every redrawn texture into art-data.js (loaded before game.js).
 *   node tools/build-art-data.js
 * Sources: textures-v2.js (blocks, tools, faces), textures-v3-missing.js (new content),
 * textures-v4-existing.js (all other existing items, armour, plants, blocks).
 * Each entry is "palette|pixels": palette = comma-separated rrggbb[aa], pixels = one char per pixel
 * from ALPH ('.' = transparent). The game decodes them in applyArtOverrides().
 */
const fs = require('fs');
const path = require('path');
const V2 = require('./textures-v2.js');
const V3 = require('./textures-v3-missing.js');
const V4 = require('./textures-v4-existing.js');
const ALPH = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz+/*#$%&=?@!~^';

function enc({ w, h, px }) {
  const pal = [], idx = new Map(); let s = '';
  for (let i = 0; i < px.length; i += 4) {
    const [r, g, b, a] = [px[i], px[i + 1], px[i + 2], px[i + 3]];
    if (!a) { s += '.'; continue; }
    const k = [r, g, b].map(v => v.toString(16).padStart(2, '0')).join('') + (a < 255 ? a.toString(16).padStart(2, '0') : '');
    if (!idx.has(k)) { idx.set(k, pal.length); pal.push(k); }
    if (idx.get(k) >= ALPH.length) throw new Error('too many colours');
    s += ALPH[idx.get(k)];
  }
  return `${w}x${h}|${pal.join(',')}|${s}`;
}

const tiles = {};
for (const [k, px] of Object.entries(V2.T)) tiles[k] = enc({ w: 16, h: 16, px });
for (const [k, v] of Object.entries(V3.BLOCKS)) tiles[k] = enc(v);
for (const [k, v] of Object.entries(V3.ITEMS)) tiles[k] = enc(v);
for (const [k, v] of Object.entries(V4.ART)) tiles[k] = enc(v);

// Mob face skins: game skin key -> art. (The trader keeps its checked hood; its face is the villager's.)
const FACE_KEY = { pig: 'kh_pig_face', cow: 'kh_cow_face', chicken: 'kh_chicken_face', horse: 'horse_face', villager: 'villager_face',
  zombie: 'kh_zombie_face', skeleton: 'skel_face', yeak: 'kh_yeak_face', preay: 'kh_preay_face', tiger: 'kh_tiger_face',
  laterite_spirit: 'kh_creeper_face', dvarapala: 'kh_golem_face' };
const faces = {};
for (const [k, key] of Object.entries(FACE_KEY)) faces[key] = enc(V2.FACES[k]);
for (const [k, v] of Object.entries(V3.FACES)) faces['new_' + k + '_face'] = enc(v);

const out = `/* Generated by tools/build-art-data.js — do not edit by hand. */\nwindow.ANGKOR_ART = ${JSON.stringify({ alph: ALPH, tiles, faces })};\n`;
fs.writeFileSync(path.join(__dirname, '..', 'art-data.js'), out);
console.log('tiles', Object.keys(tiles).length, 'faces', Object.keys(faces).length, (out.length / 1024).toFixed(1) + ' KB');
